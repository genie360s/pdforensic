"""Regenerate tests/fixtures/*.pdf with real PDF producers.

Run by hand (not in CI); the outputs are committed so the test suite needs
none of these tools:

    uv run --with reportlab --with fpdf2 --with pillow tests/make_fixtures.py

Also uses, when present: mutool (MuPDF), Google Chrome, cupsfilter (macOS).
"""

import io
import pathlib
import shutil
import subprocess
import sys
import tempfile

OUT = pathlib.Path(__file__).parent / "fixtures"
CHROME = "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome"


def reportlab_pdf():
    from reportlab.pdfgen import canvas
    buf = io.BytesIO()
    c = canvas.Canvas(buf, invariant=1)
    c.setTitle("Invoice 0042")
    c.setAuthor("Billing System")
    c.drawString(72, 720, "Invoice 0042 - total due 120.00")
    c.showPage()
    c.save()
    return buf.getvalue()


def main():
    import pikepdf
    from fpdf import FPDF
    from PIL import Image

    OUT.mkdir(exist_ok=True)
    made = {}
    base = reportlab_pdf()
    made["reportlab.pdf"] = base

    pdf = FPDF()
    pdf.add_page()
    pdf.set_font("Helvetica", size=14)
    pdf.cell(text="Statement generated by fpdf2")
    made["fpdf2.pdf"] = bytes(pdf.output())

    buf = io.BytesIO()
    Image.new("RGB", (64, 64), (200, 30, 30)).save(buf, "PDF")
    made["pillow_image.pdf"] = buf.getvalue()

    def qpdf(**save):
        out = io.BytesIO()
        with pikepdf.open(io.BytesIO(base)) as doc:
            doc.save(out, **save)
        return out.getvalue()

    made["qpdf_linearized.pdf"] = qpdf(linearize=True)
    made["qpdf_objstm.pdf"] = qpdf(object_stream_mode=pikepdf.ObjectStreamMode.generate)
    made["qpdf_rc4_128.pdf"] = qpdf(encryption=pikepdf.Encryption(owner="owner", user="", R=3, aes=False, metadata=False))
    made["qpdf_aes128.pdf"] = qpdf(encryption=pikepdf.Encryption(owner="owner", user="", R=4))
    made["qpdf_aes256.pdf"] = qpdf(encryption=pikepdf.Encryption(owner="owner", user="", R=6))
    made["qpdf_aes256_userpw.pdf"] = qpdf(encryption=pikepdf.Encryption(owner="owner", user="secret", R=6))

    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        if shutil.which("mutool"):
            # MuPDF appends an incremental update when asked to save incrementally.
            for name, source in (("mutool_incremental.pdf", base), ("linearized_then_updated.pdf", made["qpdf_linearized.pdf"])):
                target = tmp / name
                target.write_bytes(source)
                script = tmp / "edit.js"
                script.write_text(
                    'var doc = Document.openDocument(scriptArgs[0]);\n'
                    'var info = doc.getTrailer().get("Info");\n'
                    'info.put("Title", doc.newString("Invoice 0042 (amended)"));\n'
                    'info.put("Producer", doc.newString("MuPDF incremental save"));\n'
                    'doc.save(scriptArgs[0], "incremental");\n')
                subprocess.run(["mutool", "run", str(script), str(target)], check=True)
                made[name] = target.read_bytes()
        if pathlib.Path(CHROME).exists():
            html = tmp / "page.html"
            html.write_text("<html><head><title>Web receipt</title></head><body><h1>Receipt</h1><p>Paid 15.00</p></body></html>")
            target = tmp / "chrome.pdf"
            subprocess.run([CHROME, "--headless", "--disable-gpu", "--no-pdf-header-footer",
                            "--print-to-pdf=%s" % target, html.as_uri()], check=True, capture_output=True)
            made["chrome_headless.pdf"] = target.read_bytes()
        if shutil.which("cupsfilter") and sys.platform == "darwin":
            text = tmp / "note.txt"
            text.write_text("Printed through the macOS print pipeline.\n")
            result = subprocess.run(["cupsfilter", "-m", "application/pdf", str(text)], capture_output=True)
            if result.stdout.startswith(b"%PDF"):
                made["macos_quartz.pdf"] = result.stdout

    for name, data in sorted(made.items()):
        (OUT / name).write_bytes(data)
        print("%-32s %7d bytes" % (name, len(data)))


if __name__ == "__main__":
    main()
